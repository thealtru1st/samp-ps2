#!/usr/bin/env python3
"""payload.bin -> PCSX2 pnach. The payload itself is written once at ELF entry
(place 0); the stub and hook are re-asserted continuously (place 2 is idempotent)."""
import struct, sys, os
root=os.path.join(os.path.dirname(__file__),'..')
pay=open(os.path.join(root,'private','payload.bin'),'rb').read()
LOAD=0x82000000; STUB=0x000FFF00; SITE=0x00246770
def lui(r,v): return 0x3c000000|(r<<16)|(v&0xffff)
def ori(r,v): return 0x34000000|(r<<21)|(r<<16)|(v&0xffff)
stub=[lui(25,LOAD>>16), ori(25,LOAD&0xffff), 0x03200008, 0]   # jr t9 ; nop
jal=0x0c000000|((STUB>>2)&0x3ffffff)
# Runs when main.scm has just been read (replaces the file-close call in
# CTheScripts::Init): plants TERMINATE_THIS_SCRIPT at offset 0xDC71, just before the
# script launches the INITIAL and INTRO missions. Startup up to there still runs, so
# the player, camera and relationships are created by the game's own code.
STOP=0x000FFF20; STOP_SITE=0x001F8E5C; STOP_ADDR=0x006B2070+0xDC71
def sb(rt,off,base): return 0xA0000000|(base<<21)|(rt<<16)|off
stop=[lui(25,STOP_ADDR>>16), ori(25,STOP_ADDR&0xffff), 0x34000000|(24<<16)|0x4E, sb(24,0,25), sb(0,1,25),
      lui(25,0x0023), ori(25,0x3370), 0x03200008, 0]
L=['gametitle=GTA San Andreas (SLES-52927) SA-MP PS2 payload','comment=generated by tools/mkpnach.py','']
CH=2048
for i in range(0,len(pay),CH):
    L.append('patch=0,EE,%08X,bytes,%s'%(LOAD+i,pay[i:i+CH].hex().upper()))
for i,w in enumerate(stub):
    L.append('patch=2,EE,%08X,word,%08X'%(STUB+i*4,w))
L.append('patch=2,EE,%08X,word,%08X'%(SITE,jal))
L.append('patch=2,EE,002457C0,word,00000000') # skip the logo and intro movies
# 2D render pass: replaces the DrawFonts call in Render2dStuffAfterFade.
DRAW=0x000FFF50; DRAW_SITE=0x00247318; DRAW_ENTRY=LOAD+8
draw=[lui(25,DRAW_ENTRY>>16), ori(25,DRAW_ENTRY&0xffff), 0x03200008, 0]
for i,w in enumerate(draw):
    L.append('patch=2,EE,%08X,word,%08X'%(DRAW+i*4,w))
L.append('patch=2,EE,%08X,word,%08X'%(DRAW_SITE,0x0c000000|((DRAW>>2)&0x3ffffff)))
# Pad read: first call in CGame::Process. A shared "jr ra" lets the payload return to
# the caller after it has called the displaced function itself.
PAD=0x000FFF70; PAD_SITE=0x0024338C; PAD_ENTRY=LOAD+16; RET=0x000FFF60
pad=[lui(25,PAD_ENTRY>>16), ori(25,PAD_ENTRY&0xffff), 0x03200008, 0]
for i,w in enumerate(pad):
    L.append('patch=2,EE,%08X,word,%08X'%(PAD+i*4,w))
L.append('patch=2,EE,%08X,word,%08X'%(RET,0x03E00008))
L.append('patch=2,EE,%08X,word,%08X'%(RET+4,0))
L.append('patch=2,EE,%08X,word,%08X'%(PAD_SITE,0x0c000000|((PAD>>2)&0x3ffffff)))
for i,w in enumerate(stop):
    L.append('patch=2,EE,%08X,word,%08X'%(STOP+i*4,w))
L.append('patch=2,EE,%08X,word,%08X'%(STOP_SITE,0x0c000000|((STOP>>2)&0x3ffffff)))
out=sys.argv[1] if len(sys.argv)>1 else os.path.join(
    os.environ.get('PCSX2_PATCHES') or os.path.join(os.path.expanduser('~'),'Documents','PCSX2','patches'),
    'SLES-52927_A3EF1321.pnach')
open(out,'w').write('\n'.join(L)+'\n')
print('wrote',out,len(pay),'bytes')
