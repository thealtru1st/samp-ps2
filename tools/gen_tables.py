#!/usr/bin/env python3
"""Generate payload/sampdata.h from open.mp's SAMPRakNet.cpp (MPL-2.0): the packet
cipher table and the auth challenge table. Generated at build time so the data's
origin stays explicit."""
import re, os
root=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..')
s=open(os.path.join(root,'ref','openmp-raknet','SAMPRakNet.cpp'),encoding='utf-8').read()
m=re.search(r'key\[256\]\s*=\s*\{(.*?)\};',s,re.S)
key=[int(x,16) for x in re.findall(r'0x[0-9A-Fa-f]{2}',m.group(1))]
assert len(key)==256 and sorted(key)==list(range(256)),'key table is not a permutation'
inv=[0]*256
for i,v in enumerate(key): inv[v]=i
auth=re.findall(r'\{\s*"([0-9A-F]+)",\s*"([0-9A-F]+)"\s*\}',s)
assert len(auth)==256,len(auth)
L=['/* GENERATED by tools/gen_tables.py from open.mp RakNet SAMPRakNet.cpp (MPL-2.0). */','#pragma once',
   'static const unsigned char samp_encr[256] = {'+','.join(str(v) for v in inv)+'};',
   'static const struct { const char *send, *recv; } samp_auth[256] = {']
L+=['{"%s","%s"},'%a for a in auth]+['};','']
open(os.path.join(root,'payload','sampdata.h'),'w').write('\n'.join(L))
print('ok: cipher permutation valid, auth entries',len(auth),'unique challenges',len({a for a,_ in auth}))
