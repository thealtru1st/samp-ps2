#!/usr/bin/env python3
"""Generates payload/feat_world_models.h: PC model id -> PS2 model id.

The PS2 disc numbers about 6000 objects differently from the PC game (country,
LA East, interiors...), and every server speaks PC ids. Names are the same, so the
map is built by name: PS2 ids from the IDE files on the disc, PC ids from the table at
https://wiki.multitheftauto.com/wiki/IDE_List saved as HTML.

  gen_modelmap.py IDE_DIR PC_LIST_HTML OUT.h
IDE_DIR is any folder holding the disc's *.IDE files. Only numbers go in the output."""
import os, re, sys

SECTIONS = ('objs', 'tobj', 'anim', 'peds', 'cars', 'weap', 'hier')
SKIP = ('path', '2dfx', 'txdp', 'tanm')
SAMP_ADDED = range(11682, 11754)     # 18631 and up are past the end of the table anyway
PC_LAST = 18630


def ps2_ids(root):
    ids = {}
    for r, _, fs in os.walk(root):
        for f in fs:
            if not f.upper().endswith('.IDE'):
                continue
            sec = None
            for line in open(os.path.join(r, f), errors='replace'):
                line = line.strip()
                t = line.lower()
                if not line or line.startswith('#'):
                    continue
                if t in SECTIONS or t in SKIP:
                    sec = t
                elif t == 'end':
                    sec = None
                elif sec in SECTIONS:
                    p = [x.strip() for x in line.split(',')]
                    if p[0].isdigit():
                        ids[int(p[0])] = p[1].lower()
    return ids


def pc_ids(path):
    text = open(path, encoding='utf8', errors='replace').read()
    rows = re.findall(r'<td><b>(\d+)</b></td>\s*<td>\s*([^<\n]*?)\s*</td>', text)
    return {int(a): b.lower() for a, b in rows}


def build(ps, pc):
    by_name = {}
    for i, n in ps.items():
        by_name.setdefault(n, i)
    m = {i: by_name[n] for i, n in pc.items() if n in by_name}
    claimed = set(pc.values())
    for i in range(0, PC_LAST + 1):
        if i in pc or i in SAMP_ADDED:
            continue
        lo = next((j for j in range(i - 1, -1, -1) if j in m), None)
        hi = next((j for j in range(i + 1, PC_LAST + 1) if j in m), None)
        d = m[lo] - lo if lo is not None else 0
        if lo is None or hi is None or m[hi] - hi != d:
            d = 0
        if i + d in ps and ps[i + d] not in claimed:
            m[i] = i + d
    return m


def segments(m):
    out = []
    for i in sorted(m):
        d = m[i] - i
        if out and out[-1][1] == i - 1 and out[-1][2] == d:
            out[-1][1] = i
        else:
            out.append([i, i, d])
    return out


def main():
    ps = ps2_ids(sys.argv[1])
    pc = pc_ids(sys.argv[2])
    m = build(ps, pc)
    seg = segments(m)
    same = sum(1 for k, v in m.items() if k == v)
    with open(sys.argv[3], 'w', newline='\n') as o:
        o.write('/* Generated by wip/world/gen_modelmap.py. Do not edit.\n')
        o.write(' * PC model id to PS2 model id: ids lo..hi are id + delta. Ids in no\n')
        o.write(' * segment do not exist on the PS2 disc. %d ids, %d of them moved. */\n'
                % (len(m), len(m) - same))
        o.write('#define WORLD_MODEL_SEGS %d\n' % len(seg))
        o.write('static const struct { unsigned short lo, hi; short delta; } world_model_seg[] = {\n')
        for i in range(0, len(seg), 4):
            o.write('    ' + ' '.join('{%d,%d,%d},' % tuple(s) for s in seg[i:i + 4]) + '\n')
        o.write('};\n\n')
        o.write('static int world_model_lookup(int pc)\n{\n')
        o.write('    int lo = 0, hi = WORLD_MODEL_SEGS - 1;\n\n')
        o.write('    while (lo <= hi) {\n')
        o.write('        int mid = (lo + hi) / 2;\n')
        o.write('        if (pc < world_model_seg[mid].lo)\n            hi = mid - 1;\n')
        o.write('        else if (pc > world_model_seg[mid].hi)\n            lo = mid + 1;\n')
        o.write('        else\n            return pc + world_model_seg[mid].delta;\n')
        o.write('    }\n    return -1;\n}\n')
    print(len(m), 'ids', len(seg), 'segments', len(m) - same, 'moved')
    print('in the PC list, missing on PS2:', sum(1 for i in pc if i not in m))


main()
